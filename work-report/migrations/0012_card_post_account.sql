-- 2026-08-25 대륭우체국 발송 건을 '기타'에서 '통신'으로 옮긴다.
--
-- 노션에서는 이 한 건만 '기타'로 잡혀 있었다. 같은 우체국에서 한 다른 발송
-- 네 건(05-21, 06-25, 07-27, 07-28, 09-01)은 모두 '통신'이라, 같은 성격의
-- 지출이 두 계정으로 갈라져 있었다. 노션을 옮길 때는 값을 그대로 두고
-- 사람에게 물었고, 옮기기로 정해져 여기서 바로잡는다.
--
-- id를 짚어 고친다. '기타' 전체를 옮기면 성격이 다른 지출까지 딸려 간다.
update card_expenses set account = '통신' where id = 'n03' and account = '기타';
